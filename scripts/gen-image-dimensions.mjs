// Regenerates src/lib/imageDimensions.ts from the actual files on disk.
//
// Case study images render at their natural aspect ratio (no cropping), which
// means next/image needs real width/height per file or the page reflows as
// each one loads. Paths in src/lib/projects.ts are plain strings, so there's
// no static import to infer dimensions from — hence this build-time manifest.
//
// Run after adding or replacing any project image:  node scripts/gen-image-dimensions.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();

/** Minimal JPEG SOF parser — enough for the baseline/progressive JPEGs here. */
function jpegSize(buf) {
  let i = 2; // skip SOI
  while (i < buf.length) {
    if (buf[i] !== 0xff) {
      i++;
      continue;
    }
    const marker = buf[i + 1];
    // SOF0-SOF3, SOF5-SOF7, SOF9-SOF11, SOF13-SOF15 carry the frame header.
    if (
      (marker >= 0xc0 && marker <= 0xc3) ||
      (marker >= 0xc5 && marker <= 0xc7) ||
      (marker >= 0xc9 && marker <= 0xcb) ||
      (marker >= 0xcd && marker <= 0xcf)
    ) {
      return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + buf.readUInt16BE(i + 2);
  }
  throw new Error("no JPEG SOF marker found");
}

const source = readFileSync(join(ROOT, "src/lib/projects.ts"), "utf8");
const paths = [...new Set([...source.matchAll(/"(\/projects\/[^"]+)"/g)].map((m) => m[1]))].sort();

const entries = paths.map((p) => {
  const { width, height } = jpegSize(readFileSync(join(ROOT, "public", p)));
  return `  "${p}": { width: ${width}, height: ${height} },`;
});

writeFileSync(
  join(ROOT, "src/lib/imageDimensions.ts"),
  `// GENERATED by scripts/gen-image-dimensions.mjs — do not edit by hand.
// Re-run that script after adding or replacing any project image.

export const IMAGE_DIMENSIONS: Record<string, { width: number; height: number }> = {
${entries.join("\n")}
};
`,
);

console.log(`wrote ${entries.length} entries`);
